"""
KrishiNetra Aavishkar - Dataset Audit & Validation Module
File: src/preprocessing/validate_dataset.py

Thoroughly audits, verifies, and validates the YOLO-formatted pest dataset:
  - Class 0: army worm
  - Class 1: blister beetle
  - Class 2: corn borer

Checks:
  - 1:1 Image-Annotation Correspondence (no orphans)
  - Image file integrity (OpenCV decode, PIL decode, channels, non-zero dimensions)
  - Synthetic / placeholder detection (checks for OpenCV-generated ellipse patterns)
  - Bounding box syntax (5 tokens, integer class in [0, 2], normalized coords in [0.0, 1.0])
  - Box dimensions (positive area, w > 0, h > 0)
  - Duplicate detection (SHA-256 hash comparison)
  - Data leakage check (zero image hash overlap between train/val/test)
  - Stratification & class distribution analysis
  - Outputs machine-readable JSON and human-readable Markdown reports
"""

import argparse
import hashlib
import json
import os
import sys
from collections import Counter, defaultdict
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

import cv2
import numpy as np
from PIL import Image

PROJECT_ROOT = Path(__file__).resolve().parent.parent.parent

CLASS_MAPPING = {
    0: "army worm",
    1: "blister beetle",
    2: "corn borer",
}

VALID_IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".bmp"}


def compute_file_hash(filepath: Path) -> str:
    """Compute SHA-256 hash of a file for exact duplicate and leakage detection."""
    sha = hashlib.sha256()
    with open(filepath, "rb") as f:
        while chunk := f.read(65536):
            sha.update(chunk)
    return sha.hexdigest()


def check_if_synthetic_ellipse_pattern(img_bgr: np.ndarray) -> bool:
    """
    Detect if an image is a known synthetic sample generated by
    the previous ellipse placeholder script (green noise with ellipse drawing).
    Synthetic images have distinct mathematical noise distribution.
    """
    if img_bgr.shape[0] != 640 or img_bgr.shape[1] != 640:
        return False

    # Check color channels: green channel was generated with uniform random [90, 160]
    # and red/blue with [30, 90]
    b, g, r = cv2.split(img_bgr)
    # Exclude central region where ellipse was drawn
    border_mask = np.ones((640, 640), dtype=bool)
    border_mask[100:540, 100:540] = False

    b_border = b[border_mask]
    g_border = g[border_mask]
    r_border = r[border_mask]

    # Synthetic sample background had strictly b in [30, 90], g in [90, 160], r in [30, 90]
    is_synth_bg = (
        np.all(b_border >= 25)
        and np.all(b_border <= 95)
        and np.all(g_border >= 85)
        and np.all(g_border <= 165)
        and np.all(r_border >= 25)
        and np.all(r_border <= 95)
    )
    return bool(is_synth_bg)


def validate_yolo_label_file(
    label_path: Path,
    expected_classes: Set[int] = {0, 1, 2},
) -> Tuple[bool, List[str], List[Dict[str, Any]]]:
    """
    Validate a single YOLO annotation .txt file.
    Returns: (is_valid, list_of_errors, list_of_parsed_boxes)
    """
    errors: List[str] = []
    boxes: List[Dict[str, Any]] = []

    if not label_path.exists():
        return False, [f"Label file missing: {label_path.name}"], []

    with open(label_path, "r", encoding="utf-8") as f:
        lines = [line.strip() for line in f if line.strip()]

    if not lines:
        errors.append(f"Empty label file: {label_path.name}")
        return False, errors, []

    for line_idx, line in enumerate(lines, start=1):
        parts = line.split()
        if len(parts) != 5:
            errors.append(
                f"Line {line_idx} in {label_path.name} does not have exactly 5 elements: '{line}'"
            )
            continue

        # Parse class ID
        try:
            cls_id = int(parts[0])
            if cls_id not in expected_classes:
                errors.append(
                    f"Line {line_idx} in {label_path.name}: class {cls_id} not in expected {expected_classes}"
                )
                continue
        except ValueError:
            errors.append(
                f"Line {line_idx} in {label_path.name}: class ID is not an integer: '{parts[0]}'"
            )
            continue

        # Parse bounding box coordinates
        try:
            xc, yc, w, h = map(float, parts[1:5])
        except ValueError:
            errors.append(
                f"Line {line_idx} in {label_path.name}: coordinates not floats: '{line}'"
            )
            continue

        # Check bounds [0.0, 1.0]
        coord_error = False
        for coord_name, val in [("xc", xc), ("yc", yc), ("w", w), ("h", h)]:
            if val < 0.0 or val > 1.0:
                errors.append(
                    f"Line {line_idx} in {label_path.name}: {coord_name}={val} out of bounds [0.0, 1.0]"
                )
                coord_error = True

        if w <= 0.0 or h <= 0.0:
            errors.append(
                f"Line {line_idx} in {label_path.name}: non-positive dimension w={w}, h={h}"
            )
            coord_error = True

        if not coord_error:
            boxes.append(
                {
                    "class_id": cls_id,
                    "class_name": CLASS_MAPPING.get(cls_id, f"class_{cls_id}"),
                    "bbox": [xc, yc, w, h],
                }
            )

    is_valid = len(errors) == 0 and len(boxes) > 0
    return is_valid, errors, boxes


def audit_dataset_split(
    split_name: str,
    images_dir: Path,
    labels_dir: Path,
) -> Dict[str, Any]:
    """Audit an individual split directory (train, val, or test)."""
    split_info: Dict[str, Any] = {
        "split": split_name,
        "image_count": 0,
        "label_count": 0,
        "valid_pairs": 0,
        "missing_labels": [],
        "orphan_labels": [],
        "corrupted_images": [],
        "synthetic_images": [],
        "label_errors": [],
        "class_box_counts": {0: 0, 1: 0, 2: 0},
        "image_hashes": {},  # hash -> filename
        "resolutions": [],
        "box_sizes": {"small": 0, "medium": 0, "large": 0},  # area: <0.05, 0.05-0.20, >0.20
    }

    if not images_dir.exists():
        split_info["error"] = f"Images directory does not exist: {images_dir}"
        return split_info

    image_files = {p.stem: p for p in images_dir.iterdir() if p.suffix.lower() in VALID_IMAGE_EXTS}
    label_files = {p.stem: p for p in labels_dir.iterdir() if p.suffix.lower() == ".txt"} if labels_dir.exists() else {}

    split_info["image_count"] = len(image_files)
    split_info["label_count"] = len(label_files)

    # Check missing labels (image without label)
    for stem, img_path in image_files.items():
        if stem not in label_files:
            split_info["missing_labels"].append(img_path.name)

    # Check orphan labels (label without image)
    for stem, lbl_path in label_files.items():
        if stem not in image_files:
            split_info["orphan_labels"].append(lbl_path.name)

    # Validate each image and corresponding label
    for stem, img_path in image_files.items():
        # Test image decodability with OpenCV
        img_bgr = cv2.imread(str(img_path))
        if img_bgr is None:
            split_info["corrupted_images"].append(f"{img_path.name} (cv2 decode failed)")
            continue

        h, w = img_bgr.shape[:2]
        if h <= 0 or w <= 0:
            split_info["corrupted_images"].append(f"{img_path.name} (zero dimensions: {w}x{h})")
            continue

        # Test with PIL
        try:
            with Image.open(img_path) as pil_img:
                pil_img.verify()
        except Exception as e:
            split_info["corrupted_images"].append(f"{img_path.name} (PIL verify failed: {e})")
            continue

        # Check for synthetic placeholder pattern
        if check_if_synthetic_ellipse_pattern(img_bgr):
            split_info["synthetic_images"].append(img_path.name)

        split_info["resolutions"].append((w, h))

        # Hash image for duplicate / leakage checks
        img_hash = compute_file_hash(img_path)
        split_info["image_hashes"][img_path.name] = img_hash

        # Validate label if present
        if stem in label_files:
            lbl_path = label_files[stem]
            is_valid, errors, boxes = validate_yolo_label_file(lbl_path)
            if not is_valid:
                split_info["label_errors"].extend(errors)
            else:
                split_info["valid_pairs"] += 1
                for b in boxes:
                    cls_id = b["class_id"]
                    split_info["class_box_counts"][cls_id] += 1
                    area = b["bbox"][2] * b["bbox"][3]
                    if area < 0.05:
                        split_info["box_sizes"]["small"] += 1
                    elif area <= 0.20:
                        split_info["box_sizes"]["medium"] += 1
                    else:
                        split_info["box_sizes"]["large"] += 1

    return split_info


def audit_full_dataset(dataset_dir: Path) -> Dict[str, Any]:
    """Audit the complete dataset across train, val, and test splits."""
    report: Dict[str, Any] = {
        "dataset_path": str(dataset_dir),
        "splits": {},
        "summary": {
            "total_images": 0,
            "total_labels": 0,
            "total_boxes": 0,
            "total_synthetic": 0,
            "total_corrupted": 0,
            "total_missing_labels": 0,
            "total_orphan_labels": 0,
            "data_leakage_count": 0,
            "duplicate_image_count": 0,
            "overall_class_boxes": {0: 0, 1: 0, 2: 0},
            "audit_passed": False,
        },
        "data_leakage": [],
        "duplicates": [],
    }

    all_hashes: Dict[str, List[Tuple[str, str]]] = defaultdict(list)  # hash -> [(split, filename)]

    for split in ["train", "val", "test"]:
        img_dir = dataset_dir / "images" / split
        lbl_dir = dataset_dir / "labels" / split
        split_data = audit_dataset_split(split, img_dir, lbl_dir)
        report["splits"][split] = split_data

        # Aggregate summary
        report["summary"]["total_images"] += split_data["image_count"]
        report["summary"]["total_labels"] += split_data["label_count"]
        report["summary"]["total_synthetic"] += len(split_data["synthetic_images"])
        report["summary"]["total_corrupted"] += len(split_data["corrupted_images"])
        report["summary"]["total_missing_labels"] += len(split_data["missing_labels"])
        report["summary"]["total_orphan_labels"] += len(split_data["orphan_labels"])

        for cls_id, count in split_data["class_box_counts"].items():
            report["summary"]["overall_class_boxes"][cls_id] += count
            report["summary"]["total_boxes"] += count

        for fname, hsh in split_data["image_hashes"].items():
            all_hashes[hsh].append((split, fname))

    # Check duplicates and data leakage
    for hsh, occurrences in all_hashes.items():
        if len(occurrences) > 1:
            report["summary"]["duplicate_image_count"] += len(occurrences) - 1
            report["duplicates"].append(occurrences)
            splits_seen = {s for s, f in occurrences}
            if len(splits_seen) > 1:
                report["summary"]["data_leakage_count"] += 1
                report["data_leakage"].append(
                    {
                        "hash": hsh,
                        "splits": list(splits_seen),
                        "files": occurrences,
                    }
                )

    # Determine overall audit status
    critical_errors = (
        report["summary"]["total_synthetic"] > 0
        or report["summary"]["total_corrupted"] > 0
        or report["summary"]["total_missing_labels"] > 0
        or report["summary"]["total_orphan_labels"] > 0
        or report["summary"]["data_leakage_count"] > 0
        or report["summary"]["total_images"] == 0
    )
    report["summary"]["audit_passed"] = not critical_errors

    return report


def generate_markdown_report(report: Dict[str, Any], output_path: Path) -> str:
    """Generate human-readable GitHub-flavored markdown report."""
    summary = report["summary"]
    status_icon = "PASSED" if summary["audit_passed"] else "FAILED"

    md = []
    md.append(f"# KrishiNetra Dataset Audit Report\n")
    md.append(f"**Audit Status:** {status_icon}\n")
    md.append(f"**Dataset Location:** `{report['dataset_path']}`\n\n")

    md.append("## Executive Summary\n")
    md.append("| Metric | Value | Status |")
    md.append("| :--- | :--- | :--- |")
    md.append(f"| **Total Images** | {summary['total_images']} | {'OK' if summary['total_images'] > 0 else 'EMPTY'} |")
    md.append(f"| **Total Annotations** | {summary['total_labels']} | {'OK' if summary['total_labels'] == summary['total_images'] else 'MISMATCH'} |")
    md.append(f"| **Total Bounding Boxes** | {summary['total_boxes']} | {'OK' if summary['total_boxes'] > 0 else 'EMPTY'} |")
    md.append(f"| **Synthetic Placeholder Images** | {summary['total_synthetic']} | {'DEFECT' if summary['total_synthetic'] > 0 else 'CLEAN'} |")
    md.append(f"| **Corrupted Images** | {summary['total_corrupted']} | {'DEFECT' if summary['total_corrupted'] > 0 else 'CLEAN'} |")
    md.append(f"| **Missing Label Files** | {summary['total_missing_labels']} | {'DEFECT' if summary['total_missing_labels'] > 0 else 'CLEAN'} |")
    md.append(f"| **Orphan Label Files** | {summary['total_orphan_labels']} | {'DEFECT' if summary['total_orphan_labels'] > 0 else 'CLEAN'} |")
    md.append(f"| **Duplicate Images** | {summary['duplicate_image_count']} | {'NOTE' if summary['duplicate_image_count'] > 0 else 'CLEAN'} |")
    md.append(f"| **Data Leakage (Train/Val/Test Overlap)** | {summary['data_leakage_count']} | {'DEFECT' if summary['data_leakage_count'] > 0 else 'CLEAN'} |\n")

    md.append("## Target Pest Class Breakdown\n")
    md.append("| Class ID | Pest Name | Train Boxes | Val Boxes | Test Boxes | Total Boxes |")
    md.append("| :--- | :--- | :--- | :--- | :--- | :--- |")
    for cls_id in [0, 1, 2]:
        cls_name = CLASS_MAPPING[cls_id]
        train_b = report["splits"].get("train", {}).get("class_box_counts", {}).get(cls_id, 0)
        val_b = report["splits"].get("val", {}).get("class_box_counts", {}).get(cls_id, 0)
        test_b = report["splits"].get("test", {}).get("class_box_counts", {}).get(cls_id, 0)
        total_b = summary["overall_class_boxes"].get(cls_id, 0)
        md.append(f"| `{cls_id}` | **{cls_name.title()}** | {train_b} | {val_b} | {test_b} | {total_b} |")
    md.append("\n")

    md.append("## Split Breakdown & Integrity\n")
    md.append("| Split | Images | Labels | Valid Pairs | Corrupt | Synthetic | Label Errors |")
    md.append("| :--- | :--- | :--- | :--- | :--- | :--- | :--- |")
    for split in ["train", "val", "test"]:
        s = report["splits"].get(split, {})
        md.append(
            f"| `{split}` | {s.get('image_count', 0)} | {s.get('label_count', 0)} | {s.get('valid_pairs', 0)} | "
            f"{len(s.get('corrupted_images', []))} | {len(s.get('synthetic_images', []))} | {len(s.get('label_errors', []))} |"
        )
    md.append("\n")

    if report["data_leakage"]:
        md.append("## Data Leakage Details\n")
        md.append("> [!WARNING] Images appearing across multiple splits compromise evaluation validity.\n\n")
        for leak in report["data_leakage"]:
            md.append(f"- Hash: `{leak['hash'][:12]}` appears in splits: {leak['splits']}")
            for split, fn in leak["files"]:
                md.append(f"  - `{split}/{fn}`")
        md.append("\n")

    content = "\n".join(md)
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        f.write(content)

    return content


def main() -> None:
    parser = argparse.ArgumentParser(description="Audit and validate KrishiNetra YOLO pest dataset")
    parser.add_argument(
        "--dataset-dir",
        type=str,
        default="datasets/ip102_subset",
        help="Path to YOLO dataset directory",
    )
    parser.add_argument(
        "--report-json",
        type=str,
        default="reports/dataset_audit_report.json",
        help="Path for output JSON report",
    )
    parser.add_argument(
        "--report-md",
        type=str,
        default="reports/dataset_audit_report.md",
        help="Path for output Markdown report",
    )
    parser.add_argument(
        "--fail-on-error",
        action="store_true",
        help="Exit with return code 1 if dataset audit fails",
    )
    args = parser.parse_args()

    dataset_path = (PROJECT_ROOT / args.dataset_dir).resolve()
    report_json_path = (PROJECT_ROOT / args.report_json).resolve()
    report_md_path = (PROJECT_ROOT / args.report_md).resolve()

    print(f"[DatasetAudit] Auditing dataset at: {dataset_path}")
    report = audit_full_dataset(dataset_path)

    # Save JSON report
    report_json_path.parent.mkdir(parents=True, exist_ok=True)
    with open(report_json_path, "w", encoding="utf-8") as f:
        # Convert tuples/non-serializable types for JSON
        def make_serializable(o: Any) -> Any:
            if isinstance(o, tuple):
                return list(o)
            if isinstance(o, (set, Counter)):
                return dict(o)
            return o

        json.dump(report, f, indent=2, default=make_serializable)
    print(f"[DatasetAudit] Saved JSON report to: {report_json_path}")

    # Save Markdown report
    md_content = generate_markdown_report(report, report_md_path)
    print(f"[DatasetAudit] Saved Markdown report to: {report_md_path}")

    passed = report["summary"]["audit_passed"]
    print(f"\n[DatasetAudit] Overall Audit Result: {'PASSED' if passed else 'FAILED'}")
    print(f"Total Images: {report['summary']['total_images']} | Total Boxes: {report['summary']['total_boxes']}")
    print(f"Synthetic Samples: {report['summary']['total_synthetic']} | Corrupt Images: {report['summary']['total_corrupted']}")
    print(f"Missing Labels: {report['summary']['total_missing_labels']} | Data Leakage: {report['summary']['data_leakage_count']}")

    if args.fail_on_error and not passed:
        sys.exit(1)


if __name__ == "__main__":
    main()
